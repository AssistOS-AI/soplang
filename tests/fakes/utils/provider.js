export const deterministic = (input) => {
    const n = words.length
    let h1 = 0, h2 = 0, h3 = 0
    for (let i = 0; i < input.length; i++) {
        const c = input.charCodeAt(i)
        h1 = (h1 + c) % n
        h2 = (h2 * 31 + c) % n
        h3 = (h3 * 131 + c) % n
    }
    return `${words[h1]}-${words[h2]}-${words[h3]}`
}

export default class Provider {
    constructor({name, models} = {}) {
        this.name = name
        this.models = models;
    }

    async getModels() {
        return this.models
    }

    async getTextResponse(model, prompt, options = {}) {
        return deterministic(prompt)
    }

    async getTextStreamingResponse(model, prompt, options = {}, onDataChunk) {
        for (const ch of deterministic(prompt)) {
            onDataChunk(ch)
            await new Promise(r => setTimeout(r, 100 + Math.random() * 400))
        }
    }

    async getChatCompletionResponse(model, messages, options = {}) {
        return deterministic(messages.map(m => m.content).join(' '))
    }

    async getChatCompletionStreamingResponse(model, messages, options = {}, onDataChunk) {
        await this.getTextStreamingResponse(model, messages.map(m => m.content).join(' '), options, onDataChunk)
    }
}
